drop_resource() {
  local attempted="$1" label="$2" class_name="$3" expected="$4"
  if ! $attempted; then
    return
  fi
  if ! run_sample "$label" "$class_name" "$expected"; then
    cleanup_failed=true
  fi
}

cleanup() {
  local status=$?
  trap - EXIT
  set +e
  echo 'Cleaning up resources created by this run...'
  if $attempted_conversation; then
    if [[ -z "$conversation_id" && -f "${report_dir}/CreateConversationSample.log" ]]; then
      conversation_id="$(sed -n 's/^Created conversation ID: //p' \
        "${report_dir}/CreateConversationSample.log")"
    fi
    if [[ -n "$conversation_id" ]]; then
      export SELECTAI_CONVERSATION_ID="$conversation_id"
      drop_resource true DropConversationSample \
        "$conversation_package.DropConversationSample" \
        "Drop conversation '${conversation_id}' completed: true"
    else
      echo 'Conversation creation was attempted, but no ID was returned for cleanup.' >&2
      cleanup_failed=true
    fi
  fi
  drop_resource "$attempted_team" DropTeamSample \
    "$agent_package.DropTeamSample" "Drop team '${SELECTAI_AGENT_TEAM_NAME}' completed: true"
  drop_resource "$attempted_agent" DropAgentSample \
    "$agent_package.DropAgentSample" "Drop agent '${SELECTAI_AGENT_NAME}' completed: true"
  drop_resource "$attempted_task" DropTaskSample \
    "$agent_package.DropTaskSample" "Drop task '${SELECTAI_AGENT_TASK_NAME}' completed: true"
  drop_resource "$attempted_tool" DropToolSample \
    "$agent_package.DropToolSample" "Drop tool '${SELECTAI_AGENT_TOOL_NAME}' completed: true"
  if $created_input_tool; then
    if ! run_input_tool_sample DropInputToolSample "$agent_package.DropToolSample" \
      "Drop tool '${input_tool_name}' completed: true"; then
      cleanup_failed=true
    fi
  fi
  for tool_sample in $created_extra_tools; do
    configure_extra_tool "$tool_sample"
    if ! run_extra_tool_sample "$tool_sample" "Drop-${extra_tool_class}" \
      "$agent_package.DropToolSample" "Drop tool '${extra_tool_name}' completed: true"; then
      cleanup_failed=true
    fi
  done
  drop_resource "$attempted_profile" DropProfileSample \
    "$profile_package.DropProfileSample" "Drop profile '${SELECTAI_PROFILE_NAME}' completed: true"
  if $created_credential; then
    drop_resource true DropCredentialSample \
      "$credential_package.DropCredentialSample" "Drop credential '${SELECTAI_CREDENTIAL_NAME}' completed: true"
  fi
  if $cleanup_failed; then
    echo "Cleanup was incomplete. Inspect ${report_dir} before retrying manually." >&2
    status=1
  fi
  printf 'Run logs: %s\n' "$report_dir"
  exit "$status"
}
