)

# Each additional tool uses a separate name and only the service's own inputs.
configure_extra_tool() {
  local tool_sample="$1" suffix
  case "$tool_sample" in
    rag) extra_tool_class=CreateRagToolSample; suffix=RAG ;;
    websearch) extra_tool_class=CreateWebSearchToolSample; suffix=WEB ;;
    slack) extra_tool_class=CreateSlackNotificationToolSample; suffix=SLK ;;
    email) extra_tool_class=CreateEmailNotificationToolSample; suffix=EML ;;
  esac
  extra_tool_name="${run_prefix}_${suffix}"
}

run_extra_tool_sample() (
  local tool_sample="$1"
  shift
  export SELECTAI_AGENT_TOOL_NAME="$extra_tool_name"
  unset SELECTAI_AGENT_TOOL_CREDENTIAL_NAME
  case "$tool_sample" in
    rag) export SELECTAI_PROFILE_NAME="$SELECTAI_AGENT_RAG_PROFILE_NAME" ;;
    websearch) export SELECTAI_AGENT_TOOL_CREDENTIAL_NAME="$SELECTAI_AGENT_WEBSEARCH_CREDENTIAL_NAME" ;;
