last_log=""
run_sample() {
  local label="$1" class_name="$2" expected="$3" result=0
  last_log="${report_dir}/${label}.log"
  printf '==> %s\n' "$label"
  "$java_cmd" -cp "$runtime_cp" "$class_name" > "$last_log" 2>&1 || result=$?
  if [[ "$result" -eq 0 && -n "$expected" ]] && ! grep -Fq -- "$expected" "$last_log"; then
    result=1
  fi
  if [[ "$result" -eq 0 && ! -s "$last_log" ]]; then
    result=1
  fi
  # Agent samples propagate failures. Core samples still need the legacy log check.
  # A successful agent response may legitimately contain the word ERROR.
  if [[ "$result" -eq 0 && "$class_name" != com.oracle.database.selectai.samples.agent.* ]] &&
     grep -Eq '(^|[[:space:]])ERROR[[:space:]]|Exception in thread' "$last_log"; then
    result=1
  fi
  if [[ "$label" == AgentWorkflowSample && "$result" -eq 0 ]]; then
    if ! grep -Fq 'First team response:' "$last_log" ||
       ! grep -Fq 'Workflow cleanup completed.' "$last_log"; then
      result=1
    fi
  fi
  if [[ "$result" -ne 0 ]]; then
    printf 'FAILED: %s (exit: %s; log: %s)\n' "$label" "$result" "$last_log" >&2
    tail -n 20 "$last_log" >&2
    return 1
  fi
  printf 'PASS: %s\n' "$label"
}

