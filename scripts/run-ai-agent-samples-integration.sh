    email) export SELECTAI_AGENT_TOOL_CREDENTIAL_NAME="$SELECTAI_AGENT_EMAIL_CREDENTIAL_NAME" ;;
  esac
  unset SELECTAI_AGENT_TOOL_TYPE SELECTAI_AGENT_TOOL_PARAMS_JSON
  run_sample "$@"
)

